import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));

/**
 * The only inputs a projection may read.
 *
 * The roadmap, the Board and the historical issue-resolution ledger are OUTPUTS of this
 * renderer. Reading any of them back would let a stale or hand-edited document become
 * authority over live repository state — the exact inversion this ticket exists to
 * prevent — so they are absent here by construction rather than filtered later.
 */
export const resolveViewInputs = (root = DEFAULT_ROOT) => ({
  sources: [
    "docs/issues.json",
    "docs/tickets/*/*.md",
    "scripts/resolve-execution-state.mjs"
  ],
  root
});

/** The static catalog the Board renders from. Ticket documents are the authority. */
const readCatalog = (root) => {
  const manifestPath = resolve(root, "docs/issues.json");
  if (!existsSync(manifestPath)) return { issues: [] };
  try {
    return JSON.parse(readFileSync(manifestPath, "utf8"));
  } catch {
    return { issues: [] };
  }
};

/**
 * Whether D0-004C is present in the target branch.
 *
 * Bootstrap is disabled once it is, so this must be a deterministic read of the tree and
 * never an inference from issue state, a label, or a projection. The workflow file is the
 * artifact D0-004C introduces, so its presence is the signal.
 */
export const detectD0004CMerged = (root = DEFAULT_ROOT) =>
  existsSync(resolve(root, ".github/workflows/operational-state.yml"));

const stableStringify = (value) => {
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.keys(value).sort().map((k) => `${JSON.stringify(k)}:${stableStringify(value[k])}`).join(",")}}`;
  }
  return JSON.stringify(value);
};

/**
 * Render the JSON and Markdown projections.
 *
 * Deterministic by construction: no timestamp, no current SHA, no iteration over an
 * unordered map. Two renders at one head must be byte-identical, because a projection that
 * changes without the tree changing cannot be diffed for drift.
 */
export const renderViews = (root = DEFAULT_ROOT) => {
  const catalog = readCatalog(root);
  const issues = [...(catalog.issues ?? [])].sort((a, b) => String(a.id ?? "").localeCompare(String(b.id ?? "")));

  const rows = issues.map((issue) => `| ${issue.id ?? ""} | ${issue.ticket ?? ""} | ${issue.milestone ?? ""} |`);

  const board = [
    "<!-- generated by scripts/render-execution-views.mjs — NOT AUTHORITY -->",
    "",
    "# Board (generated projection)",
    "",
    "This file is a rendered projection of the canonical static catalog. It is never an",
    "input to resolution and never overrides resolver state.",
    "",
    "| Issue | Ticket | Milestone |",
    "|---|---|---|",
    ...rows,
    ""
  ].join("\n");

  const json = {
    schema_version: 1,
    generated_by: "scripts/render-execution-views.mjs",
    authority: false,
    issues
  };

  return { board, json, serialized: stableStringify(json) };
};

const isDirectInvocation = () => {
  const entry = process.argv[1];
  return typeof entry === "string" && resolve(entry) === resolve(fileURLToPath(import.meta.url));
};

if (isDirectInvocation()) {
  const views = renderViews();
  process.stdout.write(`${views.serialized}\n`);
  process.stdout.write(`RENDER_VIEWS_PASS authority=false deterministic=true\n`);
}
