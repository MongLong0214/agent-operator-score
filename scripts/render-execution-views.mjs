import { existsSync, readFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));

/**
 * The only inputs a projection may read.
 *
 * The roadmap, the Board and the historical issue-resolution ledger are OUTPUTS of this
 * renderer. Reading any of them back would let a stale or hand-edited document become
 * authority over live repository state — the exact inversion this ticket exists to
 * prevent — so they are absent here by construction rather than filtered later.
 */
export const resolveViewInputs = (root = DEFAULT_ROOT) => ({
  sources: ["docs/issues.json"],
  root
});

/**
 * Every disk read in this module goes through here.
 *
 * A declared input set is worthless if the renderer can read around it, so this is the
 * enforcement point rather than documentation: a path absent from `resolveViewInputs` throws
 * instead of being read. Adding a source means declaring it, which is what makes
 * `roadmap-is-not-an-input` and its siblings load-bearing rather than decorative.
 */
export const readDeclaredInput = (root, relativePath) => {
  const { sources } = resolveViewInputs(root);
  if (!sources.includes(relativePath)) {
    throw new Error(`refusing to read undeclared projection input: ${relativePath}`);
  }
  const absolute = resolve(root, relativePath);
  if (relative(resolve(root), absolute).startsWith("..")) {
    throw new Error(`refusing to read outside the repository root: ${relativePath}`);
  }
  if (!existsSync(absolute)) return null;
  return readFileSync(absolute, "utf8");
};

/** The canonical static catalog. Its ticket rows are the Board's only content source. */
const readCatalog = (root) => {
  const raw = readDeclaredInput(root, "docs/issues.json");
  if (raw === null) return { tickets: [] };
  try {
    const parsed = JSON.parse(raw);
    return { tickets: Array.isArray(parsed.tickets) ? parsed.tickets : [] };
  } catch {
    return { tickets: [] };
  }
};

/**
 * Whether D0-004C is present in the target branch.
 *
 * Bootstrap is disabled once it is, so this must be a deterministic read of the tree and
 * never an inference from issue state, a label, or a projection. The workflow file is the
 * artifact D0-004C introduces, so its presence on disk is the signal.
 */
export const detectD0004CMerged = (root = DEFAULT_ROOT) =>
  existsSync(resolve(root, ".github/workflows/operational-state.yml"));

const stableStringify = (value) => {
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.keys(value).sort().map((k) => `${JSON.stringify(k)}:${stableStringify(value[k])}`).join(",")}}`;
  }
  return JSON.stringify(value);
};

const cell = (value) => String(value ?? "").replace(/\|/g, "\\|");

/**
 * Render the JSON and Markdown projections.
 *
 * Deterministic by construction: no timestamp, no current SHA, no iteration over an
 * unordered map, and an explicit sort by ticket id. Two renders at one head must be
 * byte-identical, because a projection that changes without the tree changing cannot be
 * diffed for drift.
 */
export const renderViews = (root = DEFAULT_ROOT) => {
  const { tickets } = readCatalog(root);
  const ordered = [...tickets].sort((a, b) => String(a.id ?? "").localeCompare(String(b.id ?? "")));

  const rows = ordered.map((ticket) => {
    const deps = Array.isArray(ticket.dependencies) ? ticket.dependencies.join(", ") : "";
    return `| ${cell(ticket.id)} | ${cell(ticket.epic)} | ${cell(ticket.milestone)} | ${cell(ticket.size)} | ${cell(deps)} |`;
  });

  const board = [
    "<!-- generated by scripts/render-execution-views.mjs — NOT AUTHORITY, NOT AN INPUT -->",
    "",
    "| Ticket | Epic | Milestone | Size | Dependencies |",
    "|---|---|---|---|---|",
    ...rows
  ].join("\n");

  const json = {
    schema_version: 1,
    generated_by: "scripts/render-execution-views.mjs",
    authority: false,
    bootstrap_disabled: detectD0004CMerged(root),
    tickets: ordered
  };

  return { board, json, serialized: stableStringify(json) };
};

const isDirectInvocation = () => {
  const entry = process.argv[1];
  return typeof entry === "string" && resolve(entry) === resolve(fileURLToPath(import.meta.url));
};

if (isDirectInvocation()) {
  const views = renderViews();
  process.stdout.write(`${views.serialized}\n`);
  process.stdout.write(
    `RENDER_VIEWS_PASS authority=false deterministic=true tickets=${views.json.tickets.length}\n`
  );
}
